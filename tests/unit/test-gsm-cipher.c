static void kgcore_start_gea3(KGCore *kgcore, uint64_t input, uint64_t kc) {
    uint8_t key[KASUMI_KEY_BYTES];

    for (size_t i = 0; i < KASUMI_KEY_BYTES; i++)
        key[i] = kc >> (56 - 8 * (i % 8));
    kgcore_start(kgcore, input, key);
}

static void test_gea12_vectors(void) {
    for (size_t v = 0; v < ARRAY_SIZE(GEA12_VECTORS); v++) {
        const GEA12Vector *vector = &GEA12_VECTORS[v];
        uint8_t ciphertext[GEA12_VECTOR_BYTES];
        GEAKeystream keystream;

        gea_start(&keystream, vector->algorithm, vector->input, vector->direction, vector->kc);
        for (size_t i = 0; i < GEA12_VECTOR_BYTES; i++)
            ciphertext[i] = vector->plaintext[i] ^ gea_next_byte(&keystream);
        g_assert_cmpmem(ciphertext, sizeof(ciphertext), vector->ciphertext, sizeof(vector->ciphertext));
    }
}

static void test_gea3_vector(void) {
    uint8_t keystream[ARRAY_SIZE(GEA3_VECTOR1_KEYSTREAM)];
    KGCore kgcore;

    kgcore_start_gea3(&kgcore, 0x8E9421A300FF0000, 0x2BD6459F82C5BC00);
    for (size_t i = 0; i < sizeof(keystream); i++)
        keystream[i] = kgcore_next_byte(&kgcore);
    g_assert_cmpmem(keystream, sizeof(keystream), GEA3_VECTOR1_KEYSTREAM, sizeof(GEA3_VECTOR1_KEYSTREAM));
}

static void test_kgcore_raw_input(void) {
    for (size_t v = 0; v < ARRAY_SIZE(KGCORE_HARDWARE_VECTORS); v++) {
        const KGCoreVector *vector = &KGCORE_HARDWARE_VECTORS[v];
        uint8_t keystream[KGCORE_PROBE_BYTES];
        KGCore kgcore;

        kgcore_start_gea3(&kgcore, vector->input, vector->kc);
        for (size_t i = 0; i < sizeof(keystream); i++)
            keystream[i] = kgcore_next_byte(&kgcore);
        g_assert_cmpmem(keystream, sizeof(keystream), vector->keystream, sizeof(vector->keystream));
    }
}

int main(int argc, char **argv) {
    g_test_init(&argc, &argv, NULL);
    g_test_add_func("/gsm-cipher/gea12-vectors", test_gea12_vectors);
    g_test_add_func("/gsm-cipher/gea3-vector", test_gea3_vector);
    g_test_add_func("/gsm-cipher/kgcore-raw-input", test_kgcore_raw_input);
    return g_test_run();
}
