static const uint8_t *pmic_revision_registers(uint32_t revision) {
	switch (revision) {
		case 0xEC:
			return regs_D1094EC;
		case 0xED:
			return regs_D1094ED;
		case 0xDB:
			return regs_D1094DB;
		case 0xBB:
			return regs_D1094BB;
		case 0xAA:
			return regs_D1601AA;
		default:
			return NULL;
	}
}

static void pmic_load_registers(pmb887x_pmic_t *p) {
	const uint8_t *registers = pmic_revision_registers(p->revision);
	g_assert(registers);
	memcpy(p->regs, registers, sizeof(p->regs));
}

static int pmic_event(I2CTarget *target, enum i2c_event event) {
	pmb887x_pmic_t *p = PMB887X_PMIC(OBJECT(target));

	switch (event) {
		case I2C_START_SEND:
			p->wcycle = 0;
			break;
		case I2C_START_SEND_ASYNC:
			p->wcycle = 0;
			break;
		case I2C_START_RECV:
			p->wcycle = 0;
			break;
		case I2C_NACK:
			p->wcycle = 0;
			break;
		case I2C_FINISH:
			p->wcycle = 0;
			break;
	}

	return 0;
}

static uint8_t pmic_recv(I2CTarget *target) {
	pmb887x_pmic_t *p = PMB887X_PMIC(OBJECT(target));
	uint8_t data = p->regs[p->reg_id];
	DEBUG_IO_READ(&p->dbg, p->reg_id, 1, data);
	p->reg_id = (p->reg_id + 1) % ARRAY_SIZE(p->regs);
	return data;
}

static int pmic_send(I2CTarget *target, uint8_t data) {
	pmb887x_pmic_t *p = PMB887X_PMIC(OBJECT(target));
	if (p->wcycle == 0) {
		p->reg_id = data % ARRAY_SIZE(p->regs);
	} else {
		DEBUG_IO_WRITE(&p->dbg, p->reg_id, 1, data);
		p->regs[p->reg_id] = data;
		pasic_audio_register_write(p, p->reg_id, data);
		p->reg_id = (p->reg_id + 1) % ARRAY_SIZE(p->regs);
	}

	p->wcycle++;

	return 0;
}

static void pmic_reset(DeviceState *dev) {
	pmb887x_pmic_t *p = PMB887X_PMIC(dev);

	qemu_set_irq(p->on_off_out, !p->on_pressed);
	p->reg_id = 0;
	p->wcycle = 0;
	p->i2s_capture_unimplemented_reported = false;
	memset(p->source_formats, 0, sizeof(p->source_formats));
	memset(p->source_gains_db, 0, sizeof(p->source_gains_db));
	pasic_routes_update(p);

	pmic_load_registers(p);
	p->output_gains[PASIC_OUTPUT_MONO] = PASIC_GAIN_MUTE;
	p->output_gains[PASIC_OUTPUT_STEREO] = PASIC_GAIN_MUTE;
	for (size_t reg = 0; reg < ARRAY_SIZE(p->regs); reg++)
		pasic_audio_register_write(p, reg, p->regs[reg]);
}

static void pmic_realize(DeviceState *dev, Error **errp) {
	pmb887x_pmic_t *p = PMB887X_PMIC(dev);
	debug_channel_init_device_regs(&p->dbg, dev, &pmb887x_pasic_regs);

	if (!pmic_revision_registers(p->revision)) {
		error_setg(errp, "Unknown PMIC revision %02X", p->revision);
		return;
	}

	DEBUG_LOG(&p->dbg, "PMIC revision: %02X\n", p->revision);
	pmic_load_registers(p);
}

