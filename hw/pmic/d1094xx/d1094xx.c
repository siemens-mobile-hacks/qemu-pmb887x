struct D1094XXState {
    SysBusDevice parent_obj;
    DebugChannel dbg;
    I2CTargetPort i2c_port;
    I2SSinkPort i2s_rx_port;
    I2SSourcePort i2s_tx_port;
    AudioRouterInput line_input;
    AudioLineBus *output_buses[D1094XX_OUTPUT_COUNT];
    AudioRouter router;
    uint8_t reg;
    uint8_t wcycle;
    uint8_t regs[D1094XX_REG_COUNT];
    uint32_t revision;
    uint32_t i2c_address;
    uint8_t mono_control_outputs;
    uint8_t stereo_control_outputs;
    uint8_t line_outputs;
    uint8_t dac_mono_outputs;
    uint8_t dac_stereo_outputs;
    uint8_t output_gains[D1094XX_OUTPUT_COUNT];
    bool i2s_capture_unimplemented_reported;
    bool on_pressed;
    qemu_irq on_off_out;
};

static bool d1094xx_output_is_enabled(const D1094XXState *s, D1094XXOutput output) {
    uint8_t enabled_outputs = s->mono_control_outputs | s->stereo_control_outputs;

    if ((enabled_outputs & BIT(output)) == 0)
        return false;
    return s->output_gains[output] != D1094XX_GAIN_MUTE;
}

static uint8_t d1094xx_input_get_outputs(const D1094XXState *s, D1094XXInput input) {
    switch (input) {
        case D1094XX_INPUT_DAC:
            return s->dac_mono_outputs | s->dac_stereo_outputs;
        case D1094XX_INPUT_LINE:
            return s->line_outputs;
        default:
            g_assert_not_reached();
    }
}

static int d1094xx_output_get_gain_mb(const D1094XXState *s, D1094XXOutput output) {
    return D1094XX_GAIN_MAX_MB - D1094XX_GAIN_STEP_MB * s->output_gains[output];
}

static void d1094xx_routes_update(D1094XXState *s) {
    for (D1094XXOutput output = 0; output < D1094XX_OUTPUT_COUNT; output++) {
        bool output_enabled = d1094xx_output_is_enabled(s, output);
        int output_gain_mb = d1094xx_output_get_gain_mb(s, output);

        for (D1094XXInput input = 0; input < D1094XX_INPUT_COUNT; input++) {
            bool input_routed = (d1094xx_input_get_outputs(s, input) & BIT(output)) != 0;

            audio_router_set_route(&s->router, output, input, output_enabled && input_routed, output_gain_mb);
        }
    }
    audio_router_update(&s->router);
}

static uint8_t d1094xx_route_decode(
    D1094XXState *s,
    uint8_t reg,
    uint8_t value,
    const D1094XXRouteValue *values,
    size_t value_count
) {
    for (size_t i = 0; i < value_count; i++) {
        if (values[i].value == value)
            return values[i].outputs;
    }
    DEBUG_UNIMP(&s->dbg, "audio register %02X value %02X\n", reg, value);
    return 0;
}

static void d1094xx_audio_register_write(D1094XXState *s, uint8_t reg, uint8_t value) {
    switch (reg) {
        case D1094XX_MONO_CONTROL:
            s->mono_control_outputs = d1094xx_route_decode(s, reg,
                value & ~(D1094XX_MONO_CONTROL_RINGIN | D1094XX_MONO_CONTROL_KEY_CLICK_EN),
                D1094XX_MONO_CONTROL_VALUES, ARRAY_SIZE(D1094XX_MONO_CONTROL_VALUES));
            break;

        case D1094XX_STEREO_CONTROL:
            s->stereo_control_outputs = d1094xx_route_decode(s, reg, value & ~D1094XX_STEREO_CONTROL_RINGIN,
                D1094XX_STEREO_CONTROL_VALUES, ARRAY_SIZE(D1094XX_STEREO_CONTROL_VALUES));
            break;

        case D1094XX_SWITCH_MUX_3:
            s->line_outputs = d1094xx_route_decode(s, reg, value,
                D1094XX_LINE_ROUTE_VALUES, ARRAY_SIZE(D1094XX_LINE_ROUTE_VALUES));
            break;

        case D1094XX_SWITCH_MUX_4:
            s->dac_mono_outputs = d1094xx_route_decode(s, reg, value,
                D1094XX_DAC_MONO_ROUTE_VALUES, ARRAY_SIZE(D1094XX_DAC_MONO_ROUTE_VALUES));
            break;

        case D1094XX_SWITCH_MUX_5:
            s->dac_stereo_outputs = d1094xx_route_decode(s, reg, value,
                D1094XX_DAC_STEREO_ROUTE_VALUES, ARRAY_SIZE(D1094XX_DAC_STEREO_ROUTE_VALUES));
            break;

        case D1094XX_AMPLIFIER_GAIN_4_5:
            if ((value & D1094XX_AMPLIFIER_GAIN_4_5_PATH_4_SELECT) == 0)
                return;
            s->output_gains[D1094XX_OUTPUT_MONO] = value & D1094XX_AMPLIFIER_GAIN_4_5_GAIN;
            break;

        case D1094XX_AMPLIFIER_GAIN_7_8:
            if ((value & D1094XX_AMPLIFIER_GAIN_7_8_PATH_7_SELECT) == 0)
                return;
            s->output_gains[D1094XX_OUTPUT_STEREO] = value & D1094XX_AMPLIFIER_GAIN_7_8_GAIN;
            break;

        default:
            return;
    }
    d1094xx_routes_update(s);
}

static void d1094xx_on_off_handler(void *opaque, int _n, int level) {
    D1094XXState *s = opaque;

    s->on_pressed = level != 0;
    qemu_set_irq(s->on_off_out, !s->on_pressed);
}

static void d1094xx_i2s_configure(I2SSink *sink, const I2SFormat *format) {
    D1094XXState *s = D1094XX(OBJECT(sink));

    if (format->sample_rate_hz == 0 || (format->channels != 1 && format->channels != 2)) {
        audio_router_stop(&s->router, D1094XX_INPUT_DAC, 0);
        return;
    }
    AudioLineFormat line_format = { format->sample_rate_hz, format->channels };
    audio_router_start(&s->router, D1094XX_INPUT_DAC, 0, &line_format);
}

static void d1094xx_i2s_write(I2SSink *sink, const int16_t *samples, size_t frame_count) {
    audio_router_write(&D1094XX(OBJECT(sink))->router, D1094XX_INPUT_DAC, 0, samples, frame_count);
}

static size_t d1094xx_i2s_read(I2SSource *source, int16_t *_samples, size_t _frame_capacity) {
    D1094XXState *s = D1094XX(OBJECT(source));

    if (!s->i2s_capture_unimplemented_reported) {
        DEBUG_UNIMP(&s->dbg, "I2S capture\n");
        s->i2s_capture_unimplemented_reported = true;
    }
    return 0;
}

static const uint8_t *d1094xx_get_reset_regs(uint32_t revision) {
    switch (revision) {
        case 0xEC:
            return D1094EC_RESET_REGS;
        case 0xED:
            return D1094ED_RESET_REGS;
        case 0xDB:
            return D1094DB_RESET_REGS;
        case 0xBB:
            return D1094BB_RESET_REGS;
        case 0xAA:
            return D1601AA_RESET_REGS;
        default:
            return NULL;
    }
}

static int d1094xx_event(I2CTarget *target, enum i2c_event _event) {
    D1094XX(OBJECT(target))->wcycle = 0;
    return 0;
}

static uint8_t d1094xx_recv(I2CTarget *target) {
    D1094XXState *s = D1094XX(OBJECT(target));
    uint8_t data = s->regs[s->reg];

    DEBUG_IO_READ(&s->dbg, s->reg, 1, data);
    s->reg++;
    return data;
}

static int d1094xx_send(I2CTarget *target, uint8_t data) {
    D1094XXState *s = D1094XX(OBJECT(target));

    if (s->wcycle == 0) {
        s->reg = data;
    } else {
        DEBUG_IO_WRITE(&s->dbg, s->reg, 1, data);
        s->regs[s->reg] = data;
        d1094xx_audio_register_write(s, s->reg, data);
        s->reg++;
    }
    s->wcycle++;

    return 0;
}

static void d1094xx_reset(DeviceState *dev) {
    D1094XXState *s = D1094XX(dev);

    qemu_set_irq(s->on_off_out, !s->on_pressed);
    s->reg = 0;
    s->wcycle = 0;
    s->i2s_capture_unimplemented_reported = false;
    audio_router_reset(&s->router);

    memcpy(s->regs, d1094xx_get_reset_regs(s->revision), sizeof(s->regs));
    s->output_gains[D1094XX_OUTPUT_MONO] = D1094XX_GAIN_MUTE;
    s->output_gains[D1094XX_OUTPUT_STEREO] = D1094XX_GAIN_MUTE;
    for (size_t reg = 0; reg < ARRAY_SIZE(s->regs); reg++)
        d1094xx_audio_register_write(s, reg, s->regs[reg]);
}

static void d1094xx_realize(DeviceState *dev, Error **errp) {
    D1094XXState *s = D1094XX(dev);

    if (!d1094xx_get_reset_regs(s->revision)) {
        error_setg(errp, "Unknown PMIC revision %02X", s->revision);
        return;
    }

    debug_channel_init_device_regs(&s->dbg, dev, &d1094xx_debug_regs);
    DEBUG_LOG(&s->dbg, "PMIC revision: %02X\n", s->revision);
}

static void d1094xx_unrealize(DeviceState *dev) {
    debug_channel_cleanup(&D1094XX(dev)->dbg);
}

static const Property d1094xx_properties[] = {
    DEFINE_PROP_UINT32("addr", D1094XXState, i2c_address, D1094XX_I2C_ADDR),
    DEFINE_PROP_UINT32("revision", D1094XXState, revision, 0xAA),
};

static void d1094xx_init(Object *obj) {
    DeviceState *dev = DEVICE(obj);
    D1094XXState *s = D1094XX(obj);

    qdev_init_gpio_in_named(dev, d1094xx_on_off_handler, "ON_OFF", 1);
    qdev_init_gpio_out_named(dev, &s->on_off_out, "ON_OFF_OUT", 1);
    i2c_target_port_init(&s->i2c_port, dev, "I2C", I2C_TARGET(obj), &s->i2c_address);
    i2s_sink_port_init(&s->i2s_rx_port, dev, "I2S_RX", I2S_SINK(obj));
    i2s_source_port_init(&s->i2s_tx_port, dev, "I2S_TX", I2S_SOURCE(obj));
    s->output_buses[D1094XX_OUTPUT_MONO] = audio_line_bus_init(dev, "MONO");
    s->output_buses[D1094XX_OUTPUT_STEREO] = audio_line_bus_init(dev, "STEREO");
    audio_router_init(&s->router, s->output_buses, D1094XX_OUTPUT_COUNT, D1094XX_INPUT_COUNT, &s->dbg);
    audio_router_input_init(&s->line_input, dev, "LINE", &s->router, D1094XX_INPUT_LINE);
}

static void d1094xx_finalize(Object *obj) {
    audio_router_cleanup(&D1094XX(obj)->router);
}

static void d1094xx_class_init(ObjectClass *klass, const void *_data) {
    DeviceClass *dc = DEVICE_CLASS(klass);
    I2CTargetClass *target_class = I2C_TARGET_CLASS(klass);
    I2SSinkClass *sink_class = I2S_SINK_CLASS(klass);
    I2SSourceClass *source_class = I2S_SOURCE_CLASS(klass);

    device_class_set_props(dc, d1094xx_properties);
    dc->realize = d1094xx_realize;
    dc->unrealize = d1094xx_unrealize;
    device_class_set_legacy_reset(dc, d1094xx_reset);
    target_class->event = d1094xx_event;
    target_class->recv = d1094xx_recv;
    target_class->send = d1094xx_send;
    sink_class->configure = d1094xx_i2s_configure;
    sink_class->write = d1094xx_i2s_write;
    source_class->read = d1094xx_i2s_read;
    audio_router_sink_class_init(AUDIO_LINE_SINK_CLASS(klass));
}

