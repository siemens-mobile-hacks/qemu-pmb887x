#ifndef HW_SMARTCARD_GSM11_H
#define HW_SMARTCARD_GSM11_H

#define GSM11_CLASS 0xA0

typedef enum GSM11Instruction {
    GSM11_INS_INVALIDATE = 0x04,
    GSM11_INS_TERMINAL_PROFILE = 0x10,
    GSM11_INS_TERMINAL_RESPONSE = 0x14,
    GSM11_INS_VERIFY_CHV = 0x20,
    GSM11_INS_CHANGE_CHV = 0x24,
    GSM11_INS_DISABLE_CHV = 0x26,
    GSM11_INS_ENABLE_CHV = 0x28,
    GSM11_INS_UNBLOCK_CHV = 0x2C,
    GSM11_INS_INCREASE = 0x32,
    GSM11_INS_REHABILITATE = 0x44,
    GSM11_INS_RUN_GSM_ALGORITHM = 0x88,
    GSM11_INS_SEEK = 0xA2,
    GSM11_INS_SELECT = 0xA4,
    GSM11_INS_READ_BINARY = 0xB0,
    GSM11_INS_READ_RECORD = 0xB2,
    GSM11_INS_GET_RESPONSE = 0xC0,
    GSM11_INS_ENVELOPE = 0xC2,
    GSM11_INS_UPDATE_BINARY = 0xD6,
    GSM11_INS_UPDATE_RECORD = 0xDC,
    GSM11_INS_STATUS = 0xF2,
} GSM11Instruction;

typedef enum GSM11Status {
    GSM11_STATUS_SUCCESS = 0x9000,
    GSM11_STATUS_RESPONSE_AVAILABLE = 0x9F00,
    GSM11_STATUS_NO_EF_SELECTED = 0x9400,
    GSM11_STATUS_OUT_OF_RANGE = 0x9402,
    GSM11_STATUS_FILE_ID_NOT_FOUND = 0x9404,
    GSM11_STATUS_PATTERN_NOT_FOUND = 0x9404,
    GSM11_STATUS_FILE_INCONSISTENT = 0x9408,
    GSM11_STATUS_ACCESS_DENIED = 0x9804,
    GSM11_STATUS_CHV_CONTRADICTION = 0x9808,
    GSM11_STATUS_INVALIDATION_CONTRADICTION = 0x9810,
    GSM11_STATUS_CHV_BLOCKED = 0x9840,
    GSM11_STATUS_MAX_VALUE_REACHED = 0x9850,
    GSM11_STATUS_WRONG_LENGTH = 0x6700,
    GSM11_STATUS_WRONG_PARAMETERS = 0x6B00,
    GSM11_STATUS_CORRECT_LENGTH = 0x6C00,
    GSM11_STATUS_INS_NOT_SUPPORTED = 0x6D00,
    GSM11_STATUS_CLASS_NOT_SUPPORTED = 0x6E00,
    GSM11_STATUS_TECHNICAL_PROBLEM = 0x6F00,
} GSM11Status;

static inline bool gsm11_command_has_data(uint8_t instruction)
{
    switch (instruction) {
    case GSM11_INS_TERMINAL_PROFILE:
    case GSM11_INS_TERMINAL_RESPONSE:
    case GSM11_INS_VERIFY_CHV:
    case GSM11_INS_CHANGE_CHV:
    case GSM11_INS_DISABLE_CHV:
    case GSM11_INS_ENABLE_CHV:
    case GSM11_INS_UNBLOCK_CHV:
    case GSM11_INS_INCREASE:
    case GSM11_INS_RUN_GSM_ALGORITHM:
    case GSM11_INS_SEEK:
    case GSM11_INS_SELECT:
    case GSM11_INS_ENVELOPE:
    case GSM11_INS_UPDATE_BINARY:
    case GSM11_INS_UPDATE_RECORD:
        return true;
    default:
        return false;
    }
}

#endif
